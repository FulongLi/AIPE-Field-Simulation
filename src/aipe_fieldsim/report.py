"""Collect benchmark/model summaries into Markdown tables and a curated results folder."""
from __future__ import annotations

import json
import shutil
from pathlib import Path


def _fmt(v, digits=6):
    if v is None:
        return "-"
    if isinstance(v, bool):
        return "yes" if v else "no"
    if isinstance(v, (int,)) and not isinstance(v, bool):
        return str(v)
    try:
        v = float(v)
    except (TypeError, ValueError):
        return str(v)
    if v == 0:
        return "0"
    if abs(v) >= 1e4 or abs(v) < 1e-3:
        return f"{v:.{digits - 2}e}"
    return f"{v:.{digits}g}"


def _pct(v):
    return "-" if v is None else f"{100 * float(v):.3g} %"


def collect_summaries(runs_dir: Path | str) -> list[dict]:
    out = []
    for path in sorted(Path(runs_dir).rglob("summary.json")):
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except json.JSONDecodeError:
            continue
        data["_path"] = str(path)
        out.append(data)
    return out


def benchmark_markdown(summary: dict) -> str:
    lines = [f"### {summary['title']} (`{summary['benchmark']}`)", "", summary["description"], "",
             f"Reference: {summary['reference']}", ""]
    levels = summary["levels"]
    lines.append("Mesh levels: " + ", ".join(f"L{L['level']}: h={_fmt(L['h_m'], 4)} m, {L['elements']} elements, {L['nodes']} nodes" for L in levels))
    lines.append("")
    lines.append("| Quantity | Unit | Analytic | FEM (finest) | Rel. error | Observed order | FEM by level |")
    lines.append("| --- | --- | --- | --- | --- | --- | --- |")
    for c in summary["comparisons"]:
        by_level = ", ".join(_fmt(r["value"], 5) for r in c["levels"])
        lines.append(f"| {c['quantity']} | {c['unit']} | {_fmt(c['analytic'])} | {_fmt(c['fem_finest'])} | "
                     f"{_pct(c['rel_error_finest'])} | {_fmt(c['observed_order'], 3)} | {by_level} |")
    if summary.get("checks"):
        lines += ["", "| Check | Value | Tolerance | Passed |", "| --- | --- | --- | --- |"]
        for ch in summary["checks"]:
            lines.append(f"| {ch['name']} | {_fmt(ch['value'], 4)} | {_fmt(ch['tolerance'], 2)} | {_fmt(ch['passed'])} |")
    t = summary.get("timing", {})
    lines += ["", f"Run time: {_fmt(t.get('total_s'), 4)} s total ({', '.join(_fmt(x, 4) + ' s' for x in t.get('per_level_s', []))} per level).", ""]
    return "\n".join(lines)


def model_markdown(summary: dict) -> str:
    run_name = summary.get("_run_name", summary["model"])
    lines = [f"### {summary['title']} (`{summary['model']}`, run `{run_name}`)", "", summary["description"], ""]
    params = summary.get("parameters", {})
    if "h_W_per_m2_K" in params:
        lines.append(f"Film coefficient h = {params['h_W_per_m2_K']} W/m^2/K (supplied), ambient {params.get('T_ambient_K')} K.")
        lines.append("")
    if "interleaved" in params:
        lines.append(f"Winding arrangement: {'P/2-S-P/2 interleaved' if params['interleaved'] else 'non-interleaved P-S'}; "
                     f"N1 = {params.get('N1')}, N2 = {params.get('N2')}, I1 = {params.get('I1_A')} A peak, f = {params.get('frequency_Hz')} Hz.")
        lines.append("")
    if summary.get("status") != "executed":
        lines.append(f"Status: **{summary.get('status')}** - {summary.get('status_note', '')}")
        lines.append("")
    results = summary.get("results", {})
    if results:
        lines += ["| Quantity | Value | Unit | Note |", "| --- | --- | --- | --- |"]
        for key, item in results.items():
            if isinstance(item, dict) and "value" in item:
                lines.append(f"| {key} | {_fmt(item['value'])} | {item.get('unit', '')} | {item.get('note', '')} |")
        lines.append("")
    for ch in summary.get("checks", []):
        lines.append(f"- check `{ch['name']}`: {_fmt(ch['value'], 4)} (tolerance {_fmt(ch['tolerance'], 2)}) -> {'passed' if ch['passed'] else 'FAILED'}")
    for lim in summary.get("limitations", []):
        lines.append(f"- limitation: {lim}")
    t = summary.get("timing", {})
    if t:
        lines.append(f"- run time: {_fmt(t.get('total_s'), 4)} s")
    lines.append("")
    return "\n".join(lines)


def write_results(runs_dir: Path | str, out_dir: Path | str) -> Path:
    runs_dir, out_dir = Path(runs_dir), Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    summaries = collect_summaries(runs_dir)
    benchmarks = [s for s in summaries if "benchmark" in s]
    models = [s for s in summaries if "model" in s]
    index = {"benchmarks": [], "models": []}
    md = ["# Executed results", "", "Generated by `aipe-fieldsim report` from the `summary.json` files of executed runs. ",
          "All numbers come from real Gmsh/ElmerGrid/ElmerSolver executions recorded in the case directories "
          "(see each `case.json` for tool versions, commands and SHA-256 hashes).", ""]
    tools = None
    for s in benchmarks + models:
        src = Path(s["_path"])
        name = src.parent.name  # run folder name (keeps e.g. heatsink_h25 and heatsink_h80 apart)
        s["_run_name"] = name
        target = out_dir / name
        target.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(src, target / "summary.json")
        for png in sorted(src.parent.rglob("*.png")):
            rel = png.relative_to(src.parent)
            dest = target / "_".join(rel.parts)
            shutil.copyfile(png, dest)
        tools = tools or s.get("tools")
        entry = {"name": name, "title": s.get("title"), "summary": f"{name}/summary.json", "created_at": s.get("created_at")}
        (index["benchmarks"] if "benchmark" in s else index["models"]).append(entry)
    if tools:
        md += ["## Tool versions", ""]
        for key in ("elmersolver", "elmergrid", "gmsh"):
            info = tools.get(key, {})
            md.append(f"- {info.get('name', key)}: version {info.get('version')} ({info.get('revision') or ''} {info.get('compiled') or ''}), source {info.get('source')}, path `{info.get('path')}`")
        py = tools.get("python", {})
        md.append(f"- Python {py.get('version')} with numpy {py.get('packages', {}).get('numpy')}, scipy {py.get('packages', {}).get('scipy')}, matplotlib {py.get('packages', {}).get('matplotlib')}")
        md.append("")
    if benchmarks:
        md += ["## Benchmarks", ""]
        for s in benchmarks:
            md.append(benchmark_markdown(s))
    if models:
        md += ["## DAB-relevant models", ""]
        for s in models:
            md.append(model_markdown(s))
    (out_dir / "benchmarks.md").write_text("\n".join(md).rstrip() + "\n", encoding="utf-8")
    (out_dir / "index.json").write_text(json.dumps(index, indent=2), encoding="utf-8")
    return out_dir / "benchmarks.md"
